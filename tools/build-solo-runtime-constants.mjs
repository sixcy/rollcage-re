import {readFile, writeFile} from 'node:fs/promises';
import {loadRetainedNativeProgram} from './lib/retained-native-program.mjs';

// Package retained executable DATA only. No interpreter or fixture is shipped.
const program = await loadRetainedNativeProgram();
// The module initializers already own AI, model, angle and particle tables.
// Only shared numeric literals lack a packaged initializer.
const tables = program.tables.filter(table => Number(table.address) >= 0x5dca00 && Number(table.address) < 0x5dd100);
const evidence = [];
for (const reference of program.references.filter(reference => reference.operation === 'read_bytes')) {
  const reply = JSON.parse(await readFile(reference.path, 'utf8'));
  const normalized = (reply.structuredContent ?? JSON.parse(reply.content.find(item => item.type === 'text').text)).normalized_result;
  const start = Number(normalized.address), end = start + normalized.returned_bytes;
  if (tables.some(table => Number(table.address) < end && Number(table.address) + table.bytes_hex.length / 2 > start)) evidence.push(reference);
}
await writeFile('src/solo-runtime-constants.json', JSON.stringify({
  targetSha256: program.sha256,
  method: 'Exact retained read_bytes data spans; source identities in evidence. Generated by tools/build-solo-runtime-constants.mjs.',
  evidence,
  tables
}, null, 2) + '\n');
console.log(`Packaged ${tables.length} retained data spans.`);
